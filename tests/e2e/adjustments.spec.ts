test('verouderde aanpassing wordt niet toegepast en opslagfout kan opnieuw geprobeerd worden', async ({ page, context }) => {
  await start(page)
  const other = await context.newPage()
  await other.goto(page.url())
  await other.getByRole('button', { name: 'Lukt niet', exact: true }).click()
  await other.getByRole('button', { name: 'Bezet', exact: true }).click()
  await later(page)
  await other.getByRole('button', { name: 'Later doen', exact: true }).click()
  await expect(other.getByRole('dialog').getByRole('alert')).toContainText('ander venster')
  await other.close()
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put
    let fail = true
    IDBObjectStore.prototype.put = function (...args) {
      if (this.name === 'workoutOutbox' && fail) { fail = false; throw new DOMException('Test quota', 'QuotaExceededError') }
      return original.apply(this, args)
    }
  })
  await page.getByRole('button', { name: 'Lukt niet', exact: true }).click()
  await page.getByRole('button', { name: 'Geen materiaal', exact: true }).click()
  await page.getByRole('button', { name: 'Resterende sets overslaan' }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('opslag is vol')
  await page.getByRole('button', { name: 'Resterende sets overslaan' }).click()
  await expect(page.getByRole('heading', { name: 'Chest press', exact: true })).toBeVisible()
})
