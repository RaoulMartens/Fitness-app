test('hele training, dubbel bevestigen, verlopen rust, geweigerde wake lock en vorige registratie', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => Object.defineProperty(navigator, 'wakeLock', { value: { request: () => Promise.reject(new DOMException('Test denial', 'NotAllowedError')) } }))
  await page.clock.install({ time: new Date('2026-09-17T18:00:00Z') })
  await page.goto('/')
  await page.getByRole('button', { name: 'Start training', exact: true }).click()
  await page.getByRole('button', { name: 'Naar oefening 1' }).click()
  for (let index = 0; index < 14; index++) {
    await page.getByRole('textbox', { name: 'Gewicht (kg)' }).fill('12,5')
    await page.getByRole('textbox', { name: 'Herhalingen', exact: true }).fill('10')
    await expect(page.getByRole('status')).toHaveText('Concept op apparaat opgeslagen')
    if (index === 0) {
      await page.getByRole('button', { name: 'Set vastleggen', exact: true }).evaluate(button => { if (button instanceof HTMLButtonElement) { button.click(); button.click() } })
      await expect(page.getByRole('timer')).toHaveText('2:00')
      await page.getByRole('checkbox', { name: 'Scherm aanhouden tijdens rust' }).check()
      await expect(page.getByText('Scherm aanhouden lukt niet. Houd zelf je scherm actief.')).toBeVisible()
      await page.clock.fastForward(121_000)
      await expect(page.getByRole('heading', { name: 'Rust voorbij', exact: true })).toBeVisible()
      await page.getByRole('button', { name: '30 seconden extra rust' }).click()
      await expect(page.getByRole('timer')).toHaveText('0:30')
    } else await page.getByRole('button', { name: 'Set vastleggen', exact: true }).click()
    if (index < 13) await page.getByRole('button', { name: 'Verder trainen', exact: true }).click()
  }
  await expect(page.getByRole('heading', { name: 'Alle sets vastgelegd' })).toBeVisible()
  await expect(page.getByText('Je sessie loopt nog tot je deze afrondt.')).toBeVisible()
  await page.getByRole('button', { name: 'Sessie afronden', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Sessie afronden', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sessie afgerond', exact: true })).toBeVisible()
  await expect(page.getByText('14 van 14 werksets vastgelegd.')).toBeVisible()
  await page.reload()
  await expect(page.getByText('14 van 14 werksets vastgelegd.')).toBeVisible()
  await page.getByRole('button', { name: 'Wat betekent dit?' }).click()
  await page.getByRole('button', { name: 'Terug naar Vandaag', exact: true }).click()
  await page.getByRole('button', { name: 'Volgende training starten' }).click()
  await page.getByRole('button', { name: 'Naar oefening 1' }).click()
  await expect(page.getByRole('textbox', { name: 'Gewicht (kg)' })).toHaveValue('')
  await expect(page.getByText('Vorige registratie van set 1: 12,5 kg × 10. Alleen vergelijkbaar op hetzelfde apparaat.')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('m2-mobile.png'), fullPage: true })
  expect(errors).toEqual([])
})

