test('browser sluiten en offline heropenen behoudt actieve rust en later conceptinvoer', async ({ browserName }) => {
  const browserType = browserName === 'webkit' ? webkit : chromium
  const profile = await mkdtemp(join(tmpdir(), 'fitness-m2-'))
  const options = { headless: true, viewport: { width: 375, height: 812 } }
  let context = await browserType.launchPersistentContext(profile, options)
  try {
    let page = await context.newPage()
    await page.goto('http://127.0.0.1:4173/')
    await page.getByRole('button', { name: 'Start training', exact: true }).click()
    await page.getByRole('button', { name: 'Naar oefening 1' }).click()
    await page.getByRole('textbox', { name: 'Gewicht (kg)' }).fill('12,5')
    await page.getByRole('textbox', { name: 'Herhalingen', exact: true }).fill('10')
    await page.getByRole('button', { name: 'Set vastleggen', exact: true }).click()
    await expect(page.getByRole('timer')).toBeVisible()
    await expect(page.getByText('App offline beschikbaar', { exact: true })).toBeVisible()
    await context.close()
    context = await browserType.launchPersistentContext(profile, options)
    await context.setOffline(true)
    page = await context.newPage()
    await page.goto('http://127.0.0.1:4173/')
    await page.getByRole('button', { name: 'Verder trainen', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Verder trainen', exact: true }).click()
    await expect(page.getByRole('cell', { name: '12,5 kg × 10', exact: true })).toBeVisible()
    await expect(page.getByRole('timer')).toHaveText(/^[01]:\d\d$/)
    await page.getByRole('button', { name: 'Verder trainen', exact: true }).click()
    await page.getByRole('textbox', { name: 'Gewicht (kg)' }).fill('16,')
    await expect(page.getByRole('status')).toHaveText('Concept op apparaat opgeslagen')
    await context.close()
    context = await browserType.launchPersistentContext(profile, options)
    await context.setOffline(true)
    page = await context.newPage()
    await page.goto('http://127.0.0.1:4173/')
    await page.getByRole('button', { name: 'Verder trainen', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Verder trainen', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Gewicht (kg)' })).toHaveValue('16,')
  } finally {
    await context.close()
    const resolved = await realpath(profile)
    if (dirname(resolved) !== await realpath(tmpdir()) || !basename(resolved).startsWith('fitness-m2-')) throw new Error('Onverwachte testmap, niet verwijderd.')
    await rm(resolved, { recursive: true, maxRetries: 3, retryDelay: 300 })
  }
})
